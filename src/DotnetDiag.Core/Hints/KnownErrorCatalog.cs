    public static IReadOnlyCollection<KnownError> All => Entries.Values;

    public static KnownError? Find(string code) =>
        Entries.TryGetValue(code.Trim().ToUpperInvariant(), out var entry) ? entry : null;

    public static string DocsUrlFor(string code)
    {
        var upper = code.ToUpperInvariant();
        var lower = code.ToLowerInvariant();
        return upper switch
        {
            _ when upper.StartsWith("NU", StringComparison.Ordinal) && !upper.StartsWith("NUNIT", StringComparison.Ordinal) =>
                $"https://learn.microsoft.com/nuget/reference/errors-and-warnings/{lower}",
            _ when upper.StartsWith("NETSDK", StringComparison.Ordinal) =>
                $"https://learn.microsoft.com/dotnet/core/tools/sdk-errors/{lower}",
            _ => $"https://learn.microsoft.com/search/?terms={Uri.EscapeDataString(upper)}",
        };
    }

    private static Dictionary<string, KnownError> Build(params (string Code, string Title, string Explanation, string[] Fixes)[] entries) =>
        entries.ToDictionary(
            e => e.Code,
            e => new KnownError(e.Code, e.Title, e.Explanation, e.Fixes),
            StringComparer.OrdinalIgnoreCase);
